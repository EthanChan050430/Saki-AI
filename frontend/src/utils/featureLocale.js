function normalizeFeatureLocale(language = '') {
  const raw = String(language || '').trim();
  if (raw.startsWith('zh-TW')) return 'zh-TW';
  if (raw.startsWith('zh')) return 'zh-CN';
  if (raw.startsWith('ja')) return 'ja';
  if (raw.startsWith('fr')) return 'fr';
  if (raw.startsWith('en-GB')) return 'en-US';
  if (raw.startsWith('en')) return 'en-US';
  return 'en-US';
}

export function getFeatureLocale(language = '') {
  return featureLocales[normalizeFeatureLocale(language)] || featureLocales['en-US'];
}
